import { build } from 'esbuild';
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../', import.meta.url));
const asset = new URL('../extensions/shopkeeper-chat/assets/shopkeeper-chat.js', import.meta.url);
const result = await build({
  absWorkingDir: root,
  entryPoints: ['extensions/shopkeeper-chat/src/index.js'],
  bundle: true,
  format: 'iife',
  platform: 'browser',
  target: 'es2020',
  write: false,
  banner: { js: '// Generated by npm run build:storefront-chat. Edit extensions/shopkeeper-chat/src/ instead.' },
});
const output = result.outputFiles[0].text;

if (process.argv.includes('--check')) {
  if (await readFile(asset, 'utf8') !== output) {
    throw new Error('Storefront chat asset is stale. Run npm run build:storefront-chat.');
  }
} else {
  await writeFile(asset, output);
}
